            These are not retention ponds or freshwater lagoons. They are rare geological formations: shallow,
            irregularly shaped bodies of water sitting just inside the sand dunes that separate them from the Gulf.
            Following heavy rainfall, the lakes periodically breach their sand berms and drain directly into the
            Gulf, mixing fresh and salt water in a way that supports unusually high biodiversity along the shoreline.
          </p>
